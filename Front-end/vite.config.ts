import { createHash } from "node:crypto"
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import path from "path"
import tailwindcss from "@tailwindcss/vite"
import react from "@vitejs/plugin-react"
import { defineConfig, type Plugin } from "vite"

const PUBLIC_SHELL_FILES = new Set([
  "index.html",
  "manifest.webmanifest",
  "icons/finshare-icon.svg",
  "icons/finshare-180.png",
  "icons/finshare-192.png",
  "icons/finshare-512.png",
  "icons/finshare-maskable-192.png",
  "icons/finshare-maskable-512.png",
])

function listFiles(directory: string, root = directory): string[] {
  return readdirSync(directory).flatMap((name) => {
    const absolutePath = path.join(directory, name)
    if (statSync(absolutePath).isDirectory()) return listFiles(absolutePath, root)
    return [path.relative(root, absolutePath).replaceAll(path.sep, "/")]
  })
}

function createServiceWorker(version: string, precacheUrls: string[]): string {
  return `/* FinShare service worker. Generated by the Vite build; do not edit dist/sw.js. */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = "finshare-shell-" + VERSION;
const STATIC_CACHE = "finshare-static-" + VERSION;
const APP_SHELL = "/index.html";
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};
const PRECACHE_PATHS = new Set(PRECACHE_URLS.map((value) => new URL(value, self.location.origin).pathname));
const STATIC_URLS = PRECACHE_URLS.filter((url) => url.startsWith("/assets/"));
const SHELL_URLS = PRECACHE_URLS.filter((url) => !url.startsWith("/assets/"));
const NEVER_CACHE_PREFIXES = ["/api", "/ws", "/socket"];

function mustBypassCache(request, url) {
  if (request.method !== "GET" || url.origin !== self.location.origin) return true;
  if (NEVER_CACHE_PREFIXES.some((prefix) => url.pathname.startsWith(prefix))) return true;
  if (request.headers.has("authorization")) return true;
  return (request.headers.get("accept") || "").includes("text/event-stream");
}

async function networkFirstNavigation(request) {
  try {
    const response = await fetch(request);
    if (response.ok && response.type === "basic") {
      const cache = await caches.open(SHELL_CACHE);
      await cache.put(APP_SHELL, response.clone());
    }
    return response;
  } catch {
    return (await caches.match(APP_SHELL, { ignoreSearch: true })) || Response.error();
  }
}

async function cacheFirstStatic(request) {
  const cached = await caches.match(request, { ignoreSearch: true });
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok && response.type === "basic") {
    const cache = await caches.open(STATIC_CACHE);
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    Promise.all([
      caches.open(SHELL_CACHE).then((cache) =>
        cache.addAll(SHELL_URLS.map((url) => new Request(url, { cache: "reload" })))
      ),
      caches.open(STATIC_CACHE).then((cache) =>
        cache.addAll(STATIC_URLS.map((url) => new Request(url, { cache: "reload" })))
      ),
    ])
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((key) => key.startsWith("finshare-") && key !== SHELL_CACHE && key !== STATIC_CACHE)
        .map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (mustBypassCache(request, url)) return;

  if (request.mode === "navigate") {
    event.respondWith(networkFirstNavigation(request));
    return;
  }

  if (PRECACHE_PATHS.has(url.pathname)) {
    event.respondWith(cacheFirstStatic(request));
  }
});
`
}

function finSharePwaPlugin(): Plugin {
  return {
    name: "finshare-pwa",
    apply: "build",
    closeBundle() {
      const outputDirectory = path.resolve(__dirname, "dist")
      const files = listFiles(outputDirectory)
        .filter((file) => file.startsWith("assets/") || file.startsWith("icons/") || PUBLIC_SHELL_FILES.has(file))
        .sort()
      const hash = createHash("sha256")
      for (const file of files) {
        hash.update(file)
        hash.update(readFileSync(path.join(outputDirectory, file)))
      }
      const version = hash.digest("hex").slice(0, 16)
      const precacheUrls = files.map((file) => `/${file}`)
      writeFileSync(path.join(outputDirectory, "sw.js"), createServiceWorker(version, precacheUrls), "utf8")
    },
  }
}

